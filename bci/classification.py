"""Reusable run-held-out CSP + LDA baseline for the EEGBCI M1 epochs."""
from __future__ import annotations

from dataclasses import asdict, dataclass
import json
from pathlib import Path
from importlib.metadata import distributions
from typing import Any

import mne
import numpy as np
from mne.decoding import CSP
from sklearn.base import clone
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.pipeline import Pipeline


CLASS_MAP = {"hands": 0, "feet": 1}
CLASS_NAMES = {0: "imagined hands", 1: "imagined feet"}


@dataclass(frozen=True)
class ClassificationConfig:
    """Model and CV settings used for both M2 and fold-model replay."""

    csp_components: int = 4
    lda_solver: str = "svd"
    n_splits: int = 3
    shuffle: bool = True
    random_seed: int = 42


@dataclass(frozen=True)
class EEGDataset:
    """Validated EEG samples and metadata; y labels use hands=0, feet=1."""

    X: np.ndarray
    y: np.ndarray
    run_ids: np.ndarray
    channel_names: tuple[str, ...]
    times_s: np.ndarray
    metadata: dict[str, Any]
    epochs_path: Path
    metadata_path: Path


@dataclass(frozen=True)
class RunFold:
    """One run-held-out split generated by StratifiedGroupKFold."""

    fold_index: int
    train_indices: np.ndarray
    validation_indices: np.ndarray
    training_runs: tuple[int, ...]
    validation_run: int


def load_m1_dataset(epochs_path: Path, metadata_path: Path) -> EEGDataset:
    """Read only existing M1 artifacts and reject incompatible data early."""
    if not epochs_path.is_file():
        raise FileNotFoundError(f"M1 epochs file does not exist: {epochs_path}")
    if not metadata_path.is_file():
        raise FileNotFoundError(f"M1 metadata file does not exist: {metadata_path}")
    try:
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        with np.load(epochs_path, allow_pickle=False) as archive:
            required = {"X", "y", "run", "times_s", "channel_names"}
            missing = required - set(archive.files)
            if missing:
                raise ValueError(f"M1 epoch archive is missing arrays: {sorted(missing)}")
            X = np.asarray(archive["X"])
            raw_labels = np.asarray(archive["y"])
            run_ids = np.asarray(archive["run"])
            times_s = np.asarray(archive["times_s"])
            channel_names = tuple(str(value) for value in archive["channel_names"].tolist())
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        raise ValueError(f"Could not read M1 artifacts: {exc}") from exc

    if X.shape != (45, 64, 481):
        raise ValueError(f"Expected M1 X shape (45, 64, 481); got {X.shape}")
    if raw_labels.shape != (45,) or run_ids.shape != (45,):
        raise ValueError("M1 labels and run IDs must each contain 45 one-dimensional entries")
    if times_s.shape != (481,) or len(channel_names) != 64:
        raise ValueError("M1 time or channel metadata does not match the epoch shape")
    if not np.issubdtype(X.dtype, np.number) or not np.isfinite(X).all():
        raise ValueError("M1 EEG epochs must be finite numeric values")
    if set(raw_labels.tolist()) != set(CLASS_MAP):
        raise ValueError(f"Expected labels {sorted(CLASS_MAP)}; got {sorted(set(raw_labels.tolist()))}")
    if set(np.unique(run_ids).tolist()) != {6, 10, 14}:
        raise ValueError(f"Expected runs 6, 10, 14; got {np.unique(run_ids).tolist()}")
    try:
        stored_shape = tuple(metadata["data_shape"])
        mapping = metadata["label_mapping"]
        counts = metadata["class_counts"]
        valid_mapping = "hands" in mapping["T1"].lower() and "feet" in mapping["T2"].lower()
    except (KeyError, TypeError, AttributeError) as exc:
        raise ValueError(f"M1 metadata lacks required shape or verified label mapping: {exc}") from exc
    if stored_shape != X.shape or not valid_mapping:
        raise ValueError("M1 metadata shape or T1=hands/T2=feet mapping does not match the epoch file")
    observed = {name: int(np.count_nonzero(raw_labels == name)) for name in CLASS_MAP}
    if counts != observed or observed != {"hands": 21, "feet": 24}:
        raise ValueError(f"M1 class counts do not match expected/metadata counts: {observed}")
    if set(metadata.get("runs", [])) != {6, 10, 14}:
        raise ValueError("M1 metadata must identify participant 1 and runs 6, 10, 14")
    if metadata.get("subject") != 1:
        raise ValueError("This M2 baseline is scoped to participant 1")

    y = np.asarray([CLASS_MAP[str(label)] for label in raw_labels], dtype=np.int64)
    return EEGDataset(
        X=X,
        y=y,
        run_ids=run_ids.astype(np.int64),
        channel_names=channel_names,
        times_s=times_s,
        metadata=metadata,
        epochs_path=epochs_path,
        metadata_path=metadata_path,
    )


def make_csp_lda_pipeline(config: ClassificationConfig = ClassificationConfig()) -> Pipeline:
    """Create a fresh, unfitted CSP → LDA pipeline."""
    if not 1 <= config.csp_components <= 64:
        raise ValueError("csp_components must be between 1 and 64")
    if config.lda_solver not in {"svd", "lsqr", "eigen"}:
        raise ValueError("lda_solver must be one of svd, lsqr, eigen")
    if config.n_splits != 3:
        raise ValueError("The verified M1 experiment has three recording runs; n_splits must be 3")
    return Pipeline(
        [
            (
                "csp",
                CSP(
                    n_components=config.csp_components,
                    log=True,
                    transform_into="average_power",
                    component_order="mutual_info",
                ),
            ),
            ("lda", LinearDiscriminantAnalysis(solver=config.lda_solver)),
        ]
    )


def make_run_folds(dataset: EEGDataset, config: ClassificationConfig = ClassificationConfig()) -> list[RunFold]:
    """Build shuffled, stratified CV folds that each hold out one entire run."""
    splitter = StratifiedGroupKFold(
        n_splits=config.n_splits,
        shuffle=config.shuffle,
        random_state=config.random_seed if config.shuffle else None,
    )
    folds: list[RunFold] = []
    for index, (train, validation) in enumerate(
        splitter.split(dataset.X, dataset.y, groups=dataset.run_ids), start=1
    ):
        train_runs = tuple(sorted(int(run) for run in np.unique(dataset.run_ids[train])))
        validation_runs = tuple(sorted(int(run) for run in np.unique(dataset.run_ids[validation])))
        if set(train_runs) & set(validation_runs):
            raise RuntimeError("Run leakage detected between training and validation folds")
        if len(validation_runs) != 1:
            raise RuntimeError(f"Expected one held-out run per fold; got {validation_runs}")
        if set(np.unique(dataset.y[train])) != {0, 1} or set(np.unique(dataset.y[validation])) != {0, 1}:
            raise ValueError("Every training and validation fold must contain both classes")
        folds.append(RunFold(index, train, validation, train_runs, validation_runs[0]))
    if {fold.validation_run for fold in folds} != {6, 10, 14}:
        raise RuntimeError("Each of runs 6, 10, and 14 must be held out exactly once")
    return folds


def score_summary(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, Any]:
    """Return standard binary and macro metrics in hands/feet class order."""
    return {
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "balanced_accuracy": float(balanced_accuracy_score(y_true, y_pred)),
        "precision_positive_feet": float(precision_score(y_true, y_pred, pos_label=1, zero_division=0)),
        "recall_positive_feet": float(recall_score(y_true, y_pred, pos_label=1, zero_division=0)),
        "f1_positive_feet": float(f1_score(y_true, y_pred, pos_label=1, zero_division=0)),
        "precision_macro": float(precision_score(y_true, y_pred, average="macro", zero_division=0)),
        "recall_macro": float(recall_score(y_true, y_pred, average="macro", zero_division=0)),
        "f1_macro": float(f1_score(y_true, y_pred, average="macro", zero_division=0)),
        "confusion_matrix": confusion_matrix(y_true, y_pred, labels=[0, 1]).astype(int).tolist(),
    }


def fit_run_heldout_models(
    dataset: EEGDataset,
    config: ClassificationConfig = ClassificationConfig(),
) -> tuple[dict[int, Pipeline], list[RunFold]]:
    """Fit one model per held-out run using only the other two runs."""
    folds = make_run_folds(dataset, config)
    models: dict[int, Pipeline] = {}
    template = make_csp_lda_pipeline(config)
    for fold in folds:
        model = clone(template)
        with mne.use_log_level("ERROR"):
            model.fit(dataset.X[fold.train_indices], dataset.y[fold.train_indices])
        models[fold.validation_run] = model
    return models, folds


def generate_oof_predictions(
    dataset: EEGDataset,
    config: ClassificationConfig = ClassificationConfig(),
) -> dict[str, Any]:
    """Fit fold models and produce exactly one leakage-safe prediction per epoch."""
    models, folds = fit_run_heldout_models(dataset, config)
    n_samples = len(dataset.y)
    y_pred = np.full(n_samples, -1, dtype=np.int64)
    majority_pred = np.full(n_samples, -1, dtype=np.int64)
    decision_score = np.full(n_samples, np.nan, dtype=float)
    fold_for_sample = np.full(n_samples, -1, dtype=np.int8)
    prediction_count = np.zeros(n_samples, dtype=np.int8)
    fold_metrics: list[dict[str, Any]] = []
    fold_patterns: dict[int, np.ndarray] = {}

    for fold in folds:
        model = models[fold.validation_run]
        x_validation = dataset.X[fold.validation_indices]
        y_validation = dataset.y[fold.validation_indices]
        y_fold_pred = model.predict(x_validation).astype(np.int64)
        scores = np.asarray(model.decision_function(x_validation), dtype=float).reshape(-1)
        majority_label = int(np.bincount(dataset.y[fold.train_indices], minlength=2).argmax())
        y_pred[fold.validation_indices] = y_fold_pred
        majority_pred[fold.validation_indices] = majority_label
        decision_score[fold.validation_indices] = scores
        fold_for_sample[fold.validation_indices] = fold.fold_index
        prediction_count[fold.validation_indices] += 1
        fold_patterns[fold.fold_index] = np.asarray(model.named_steps["csp"].patterns_[: config.csp_components])
        fold_metrics.append(
            {
                "fold": fold.fold_index,
                "training_runs": list(fold.training_runs),
                "validation_run": fold.validation_run,
                "training_samples": int(len(fold.train_indices)),
                "validation_samples": int(len(fold.validation_indices)),
                "validation_class_counts": {
                    "hands_0": int(np.count_nonzero(y_validation == 0)),
                    "feet_1": int(np.count_nonzero(y_validation == 1)),
                },
                "metrics": score_summary(y_validation, y_fold_pred),
                "majority_baseline_metrics": score_summary(
                    y_validation, np.full(len(y_validation), majority_label, dtype=np.int64)
                ),
            }
        )

    if np.any(prediction_count != 1):
        raise RuntimeError("Every epoch must receive exactly one out-of-fold prediction")
    if np.any(y_pred < 0) or np.any(majority_pred < 0) or np.any(fold_for_sample < 1) or not np.isfinite(decision_score).all():
        raise RuntimeError("OOF prediction output is incomplete or non-finite")
    return {
        "y_true": dataset.y.copy(),
        "y_pred": y_pred,
        "majority_pred": majority_pred,
        "decision_score_class1": decision_score,
        "fold_id": fold_for_sample,
        "prediction_count": prediction_count,
        "fold_metrics": fold_metrics,
        "metrics": score_summary(dataset.y, y_pred),
        "majority_metrics": score_summary(dataset.y, majority_pred),
        "fold_models": models,
        "folds": folds,
        "fold_patterns": fold_patterns,
    }


def dependency_versions() -> dict[str, str]:
    """Capture package versions for the reproducibility record."""
    versions = {"python": __import__("sys").version.split()[0]}
    versions.update(
        {
            dist.metadata["Name"]: dist.version
            for dist in distributions()
            if dist.metadata.get("Name")
        }
    )
    return versions


def save_m2_artifacts(
    dataset: EEGDataset,
    result: dict[str, Any],
    config: ClassificationConfig,
    output_dir: Path,
) -> None:
    """Save M2 results separately from the immutable M1 source artifacts."""
    output_dir.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        output_dir / "out_of_fold_predictions.npz",
        sample_index=np.arange(len(dataset.y), dtype=np.int64),
        y_true=result["y_true"],
        y_pred=result["y_pred"],
        majority_baseline_pred=result["majority_pred"],
        decision_score_class1=result["decision_score_class1"],
        fold_id=result["fold_id"],
        run_id=dataset.run_ids,
        prediction_count=result["prediction_count"],
    )
    metrics = {
        "evaluation_type": "within-subject run-held-out stratified cross-validation; not an independent test set",
        "dataset": {
            "name": dataset.metadata["dataset"],
            "version": dataset.metadata["dataset_version"],
            "subject": dataset.metadata["subject"],
            "runs": dataset.metadata["runs"],
            "epochs_path": str(dataset.epochs_path),
            "metadata_path": str(dataset.metadata_path),
            "preprocessing": dataset.metadata["preprocessing"],
        },
        "class_mapping": {"0": "imagined hands", "1": "imagined feet"},
        "class_counts": {"0_hands": int(np.count_nonzero(dataset.y == 0)), "1_feet": int(np.count_nonzero(dataset.y == 1))},
        "model": {"pipeline": ["MNE CSP", "scikit-learn LDA"], **asdict(config), "csp_log": True},
        "cross_validation": {
            "splitter": "StratifiedGroupKFold",
            "group_variable": "recording run",
            "n_splits": config.n_splits,
            "shuffle": config.shuffle,
            "random_seed": config.random_seed,
            "folds": result["fold_metrics"],
        },
        "out_of_fold_metrics": result["metrics"],
        "majority_class_baseline": result["majority_metrics"],
        "oof_predictions": "out_of_fold_predictions.npz",
        "dependency_versions": dependency_versions(),
        "participant_generalization_claim": False,
    }
    (output_dir / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
